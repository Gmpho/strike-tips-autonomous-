#!/usr/bin/env node
const fs = require("fs");
const path = require("path");
const { glob } = require("fs").globSync || require("fs").readdirSync;

const KNOWLEDGE_DIR = path.resolve(__dirname, "..", "knowledge", "racing");
const OUT_DIR = path.resolve(__dirname, "..", "src", "generated");
const OUT_FILE = path.join(OUT_DIR, "racing-knowledge.ts");

function parseFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return { metadata: {}, body: content };
  const raw = match[1];
  const metadata = {};
  const lines = raw.split("\n");
  for (const line of lines) {
    const colonIdx = line.indexOf(":");
    if (colonIdx === -1) continue;
    const key = line.slice(0, colonIdx).trim();
    const val = line.slice(colonIdx + 1).trim();
    // Simple parsing for lists, strings, etc.
    if (val.startsWith("[") && val.endsWith("]")) {
      metadata[key] = val.slice(1, -1).split(",").map((s) => s.trim().replace(/^"|"$/g, ""));
    } else if (val === "true") metadata[key] = true;
    else if (val === "false") metadata[key] = false;
    else metadata[key] = val;
  }
  const body = content.slice(match[0].length);
  return { metadata, body };
}

function collectMarkdownFiles(dir, prefix = "") {
  const files = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    const relPath = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...collectMarkdownFiles(fullPath, relPath));
    } else if (entry.isFile() && entry.name.endsWith(".md")) {
      files.push({ path: fullPath, relPath });
    }
  }
  return files;
}

function generate() {
  const files = collectMarkdownFiles(KNOWLEDGE_DIR);
  const entries = [];

  for (const file of files) {
    const content = fs.readFileSync(file.path, "utf-8");
    const { metadata, body } = parseFrontmatter(content);
    entries.push({
      path: file.relPath,
      metadata,
      body: body.trim(),
    });
  }

  // Create map literal
  const mapEntries = entries.map((e) => {
    const metaJson = JSON.stringify(e.metadata);
    const bodyEscaped = e.body
      .replace(/\\/g, "\\\\")
      .replace(/`/g, "\\`")
      .replace(/\${/g, "\\${");
    return `  "${e.path}": { metadata: ${metaJson}, body: \`${bodyEscaped}\` },`;
  });

  // Build search index (all text lowercased for keyword matching)
  const searchIndexEntries = entries.map((e) => {
    const keywords = [
      ...(Array.isArray(e.metadata.tags) ? e.metadata.tags : []),
      e.metadata.title,
      e.metadata.description,
      e.path.replace(/\.md$/, "").replace(/\//g, " "),
    ]
      .filter(Boolean)
      .join(" ");
    return `  "${e.path}": ${JSON.stringify(keywords.toLowerCase())},`;
  });

  const tsSource = `// Auto-generated by scripts/build-knowledge.js — DO NOT EDIT
// Generated: ${new Date().toISOString()}

export interface KnowledgeEntry {
  metadata: Record<string, unknown>;
  body: string;
}

export const racingKnowledge: Record<string, KnowledgeEntry> = {
${mapEntries.join("\n")}
};

const searchIndex: Record<string, string> = {
${searchIndexEntries.join("\n")}
};

export function getKnowledge(path: string): KnowledgeEntry | undefined {
  return racingKnowledge[path];
}

export function listKnowledgePaths(): string[] {
  return Object.keys(racingKnowledge);
}

export function searchKnowledge(query: string): { path: string; entry: KnowledgeEntry; score: number }[] {
  const q = query.toLowerCase();
  const results: { path: string; entry: KnowledgeEntry; score: number }[] = [];
  for (const [filePath, entry] of Object.entries(racingKnowledge)) {
    const idx = searchIndex[filePath] || "";
    const body = entry.body.toLowerCase();
    let score = 0;
    if (idx.includes(q)) score += 10;
    if (body.includes(q)) score += 5;
    // Count occurrences for relevance
    const matches = body.split(q).length - 1;
    score += matches;
    if (score > 0) {
      results.push({ path: filePath, entry, score });
    }
  }
  return results.sort((a, b) => b.score - a.score);
}

export function getTrackKnowledge(trackName: string): KnowledgeEntry | undefined {
  const q = trackName.toLowerCase();
  for (const [filePath, entry] of Object.entries(racingKnowledge)) {
    if (filePath.startsWith("tracks/") && filePath.toLowerCase().includes(q)) {
      return entry;
    }
  }
  return undefined;
}

export function listTrackPaths(): string[] {
  return Object.keys(racingKnowledge).filter((p) => p.startsWith("tracks/"));
}
`;

  if (!fs.existsSync(OUT_DIR)) {
    fs.mkdirSync(OUT_DIR, { recursive: true });
  }
  fs.writeFileSync(OUT_FILE, tsSource, "utf-8");
  console.log(`OKF bundle generated: ${OUT_FILE} (${entries.length} entries)`);
}

generate();
